// Explicitly opt-in integration checks. Writes only to the supplied QA account.
import assert from 'node:assert/strict';
const origin = process.env.TRACKER_QA_ORIGIN || 'http://127.0.0.1:4173';
if (!['127.0.0.1','localhost'].includes(new URL(origin).hostname)) throw new Error('Local QA only');
const email = process.env.TRACKER_QA_EMAIL, password = process.env.TRACKER_QA_PASSWORD;
if (!email?.startsWith('tracker.qa.') || !password) throw new Error('Supply an explicit tracker.qa. account and password');
let token;
let checks = 0;
async function call(path, method = 'GET', body, expected = 200) {
  const response = await fetch(`${origin}/api${path}`, {method, headers:{'Content-Type':'application/json', ...(token ? {Authorization:`Bearer ${token}`} : {})}, ...(body ? {body:JSON.stringify(body)} : {})});
  const text = await response.text();
  assert.equal(response.status,expected,`${method} ${path}: ${text.slice(0,250)}`);
  checks++; console.log(`PASS ${method} ${path} (${expected})`);
  return text ? JSON.parse(text) : null;
}
const date = new Date(); const today = new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Kolkata'}).format(date);
const tomorrow = new Date(`${today}T12:00:00Z`); tomorrow.setUTCDate(tomorrow.getUTCDate()+1);
const next = tomorrow.toISOString().slice(0,10), prefix = `QA ${Date.now()}`;
await call('/health');
await call('/dashboard','GET',undefined,401);
await call('/auth/login','POST',{email,password:'intentionally-wrong'},401);
token = (await call('/auth/login','POST',{email,password})).token;
assert.equal((await call('/auth/me')).user.email,email);
const binary=(await call('/routines','POST',{title:`${prefix} Read`,type:'BINARY',category:'STUDY'},201)).routine;
const quantity=(await call('/routines','POST',{title:`${prefix} Water`,type:'QUANTIFIABLE',targetQuantity:3,unit:'glasses',category:'HEALTH'},201)).routine;
await call('/routines','POST',{title:`${prefix} Project`,type:'TEMPORARY',targetQuantity:5,endDate:next},201);
assert.ok((await call('/dashboard')).records.some(record=>record.routineId._id===binary._id));
assert.equal((await call(`/routines/${binary._id}/progress`,'PATCH',{completed:true})).record.completed,true);
assert.equal((await call(`/routines/${quantity._id}/progress`,'PATCH',{completedQuantity:2})).record.completedQuantity,2);
assert.equal((await call(`/routines/${quantity._id}/progress`,'PATCH',{completedQuantity:1})).record.completedQuantity,1);
await call(`/routines/${quantity._id}/progress`,'PATCH',{completedQuantity:-1},400);
await call(`/routines/${quantity._id}/skip`,'PATCH',{skipped:true});
assert.equal((await call(`/routines/${quantity._id}/skip`,'PATCH',{skipped:false})).record.skipped,false);
await call(`/routines/${quantity._id}/progress`,'PATCH',{completedQuantity:3});
await call(`/routines/${binary._id}/archive`,'POST',{});
assert.equal((await call(`/routines/${binary._id}/restore`,'POST',{})).routine.status,'ACTIVE');
assert.ok((await call(`/routines/${binary._id}/history`)).records.length);
await call(`/routines/${binary._id}`,'PATCH',{description:'QA updated description'});
const task=(await call('/tasks','POST',{title:`${prefix} Dated task`,scheduledDate:today,startTime:'09:00',deadline:'18:00',subtasks:['First step','Second step'],reminderMinutes:30},201)).task;
await call(`/tasks/${task._id}/subtasks/${task.subtasks[0]._id}`,'PATCH',{done:true});
await call(`/tasks/${task._id}/complete`,'PATCH',{completed:true});
assert.equal((await call(`/tasks/${task._id}/complete`,'PATCH',{completed:false})).task.status,'TODAY');
assert.equal((await call(`/tasks/${task._id}`,'PATCH',{scheduledDate:next,allDay:true})).task.deadline,null);
await call(`/tasks/${task._id}/outcome`,'PATCH',{outcome:'RESCHEDULED',scheduledDate:today});
await call(`/tasks/${task._id}/outcome`,'PATCH',{outcome:'SKIPPED',note:'QA intentional rest'});
const repeated=await call('/tasks','POST',{title:`${prefix} Event`,itemType:'EVENT',scheduledDate:today,allDay:true,recurrence:{frequency:'DAILY',endDate:next}},201);
assert.equal(repeated.occurrences,2);
await call('/tasks?from='+today+'&to='+next);
const mood={mood:4,energy:4,stress:2,focus:4,sleepHours:7.5,emotions:['Calm'],factors:['Study'],note:'QA persistent mood check'};
await call('/moods/'+today,'PUT',mood);
assert.equal((await call('/moods?from='+today)).entries[0].note,mood.note);
await call('/moods/analytics/overview');
await call('/productivity/plan/'+today,'PUT',{intention:'QA focus on learning',capacity:'NORMAL',priorityIds:[binary._id]});
assert.equal((await call('/productivity/overview')).plan.intention,'QA focus on learning');
const session=(await call('/productivity/focus/start','POST',{title:'QA focus',plannedMinutes:5},201)).session;
await call('/productivity/focus/start','POST',{title:'Duplicate focus'},409);
await call('/productivity/focus/'+session._id,'PATCH',{status:'ACTIVE',distractions:1});
await call('/productivity/focus/'+session._id,'PATCH',{status:'COMPLETED',durationMinutes:1});
const goal=(await call('/productivity/goals','POST',{title:`${prefix} Goal`,milestones:['Read','Practice']},201)).goal;
await call(`/productivity/goals/${goal._id}/milestones/${goal.milestones[0]._id}`,'PATCH',{done:true});
assert.equal((await call(`/productivity/goals/${goal._id}/milestones/${goal.milestones[1]._id}`,'PATCH',{done:true})).goal.status,'COMPLETED');
assert.equal((await call(`/productivity/goals/${goal._id}/milestones/${goal.milestones[0]._id}`,'PATCH',{done:false})).goal.status,'ACTIVE');
const weekly=await call('/productivity/weekly-review');
await call('/productivity/weekly-review/'+weekly.snapshot.weekStart,'PUT',{wins:'QA review saved',rating:4});
assert.equal((await call('/productivity/weekly-review')).review.wins,'QA review saved');
await call('/analytics/overview');
await call('/productivity/export');
const calendar=await fetch(`${origin}/api/productivity/calendar.ics`,{headers:{Authorization:`Bearer ${token}`}});
assert.equal(calendar.status,200); assert.match(await calendar.text(),/BEGIN:VCALENDAR/); checks++;
token=(await call('/auth/login','POST',{email,password})).token;
assert.ok((await call('/routines')).routines.some(item=>item._id===binary._id));
console.log(`SUCCESS ${checks} checks. QA records retained under ${email}.`);
