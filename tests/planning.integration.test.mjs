import test from 'node:test';
import jwt from 'jsonwebtoken';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { setTimeout as wait } from 'node:timers/promises';

test('local MongoDB: authentication, task persistence, isolation, sync conflicts, retry and deletion', { timeout: 90000 }, async t => {
  const port = 5058;
  const server = spawn(process.execPath, ['server/server.js'], { env: { ...process.env, PORT: String(port), MONGODB_URI: 'mongodb://127.0.0.1:27017/tracker_simplification_test', JWT_SECRET: 'local-integration-test-only', AI_ENABLED: 'false' }, stdio: 'pipe' });
  let logs = ''; server.stdout.on('data', chunk => logs += chunk); server.stderr.on('data', chunk => logs += chunk);
  t.after(() => server.kill());
  const base = `http://127.0.0.1:${port}/api`;
  for (let count = 0; count < 60; count++) {
    if (await fetch(`${base}/health`).then(r => r.ok).catch(() => false)) break;
    if (count === 59) assert.fail(logs);
    await wait(250);
  }
  async function call(path, { token, method = 'GET', body, status = 200 } = {}) {
    const response = await fetch(base + path, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
    const data = await response.json();
    assert.equal(response.status, status, `${method} ${path}: ${JSON.stringify(data)}\n${logs}`);
    return data;
  }
  const password = 'Local-test-password-2026';
  const email = `planning-${randomUUID()}@example.invalid`;
  const a = await call('/auth/register', { method: 'POST', body: { name: 'Planning QA', email, password }, status: 201 });
  const b = await call('/auth/register', { method: 'POST', body: { name: 'Other user', email: `other-${randomUUID()}@example.invalid`, password }, status: 201 });
  const token = a.token;
  await call('/tasks', { status: 401 });
  await call('/tasks', { token: 'broken', status: 401 });
  await call('/tasks', { token: jwt.sign({ id: a.user.id }, 'local-integration-test-only', { expiresIn: -1 }), status: 401 });
  await call('/auth/login', { method: 'POST', body: { email, password: 'wrong' }, status: 401 });
  assert.ok((await call('/auth/login', { method: 'POST', body: { email, password } })).token);
  await call('/auth/register', { method: 'POST', body: { name: 'Bad', email: 'invalid', password }, status: 400 });
  await call('/tasks', { token, method: 'POST', body: { title: 'Bad date', scheduledDate: '2026-02-30' }, status: 400 });
  await call('/tasks', { token, method: 'POST', body: { title: 'Bad progress', taskType: 'MEASURABLE', target: 5, progress: 6 }, status: 400 });
  const repeated = await call('/tasks', { token, method: 'POST', body: { title: 'Daily reading', scheduledDate: '2026-10-15', recurrence: { frequency: 'DAILY', endDate: '2026-10-17' }, subtasks: ['Open book'] }, status: 201 });
  assert.equal(repeated.occurrences, 3);
  const checklist = repeated.task.subtasks[0];
  const checked = await call(`/tasks/${repeated.task._id}/subtasks/${checklist._id}`, { token, method: 'PATCH', body: { done: true } });
  assert.equal(checked.task.subtasks[0].done, true);
  const resolved = await call(`/tasks/${repeated.task._id}/outcome`, { token, method: 'PATCH', body: { outcome: 'RESCHEDULED', scheduledDate: '2026-10-20' } });
  assert.equal(resolved.task.scheduledDate, '2026-10-20');
  assert.ok(resolved.task.revision > checked.task.revision);
  await call(`/tasks/${repeated.task._id}?series=true`, { token, method: 'DELETE' });
  let { task } = await call('/tasks', { token, method: 'POST', body: { title: 'Solve questions', scheduledDate: '2026-10-15', taskType: 'MEASURABLE', target: 5, progress: 2, unit: 'questions' }, status: 201 });
  assert.equal(task.progress, 2);
  await call(`/tasks/${task._id}`, { token: b.token, method: 'PATCH', body: { title: 'stolen' }, status: 404 });
  await call(`/tasks/${task._id}`, { token: b.token, method: 'DELETE', status: 404 });
  assert.equal((await call('/tasks', { token: b.token })).tasks.length, 0);
  const before = task.revision;
  task = (await call(`/tasks/${task._id}`, { token, method: 'PATCH', body: { progress: 5, scheduledDate: '2026-10-16' } })).task;
  assert.equal(task.status, 'COMPLETED'); assert.ok(task.revision > before);
  assert.equal((await call('/tasks?from=2026-10-16&to=2026-10-16', { token })).tasks[0].progress, 5);
  task = (await call(`/tasks/${task._id}/complete`, { token, method: 'PATCH', body: { completed: false } })).task;
  assert.equal(task.progress, 0);
  const syncId = randomUUID();
  const mutation = { entityType: 'task', operation: 'upsert', syncId, baseRevision: 0, mutationId: randomUUID(), payload: { task: { title: 'Offline task', originalDate: '2026-10-15', scheduledDate: '2026-10-15', taskType: 'MEASURABLE', target: 5, progress: 2, unit: 'questions' } } };
  const push = changes => call('/sync/push', { token, method: 'POST', body: { mutations: changes } });
  assert.equal((await push([mutation])).accepted.length, 1);
  assert.equal((await push([mutation])).accepted.length, 1);
  let records = (await call('/tasks', { token })).tasks;
  assert.equal(records.filter(record => record.syncId === syncId).length, 1);
  const remote = records.find(record => record.syncId === syncId);
  await call(`/tasks/${remote._id}`, { token, method: 'PATCH', body: { title: 'Website edit' } });
  const stale = { ...mutation, baseRevision: remote.revision, mutationId: randomUUID(), payload: { task: { ...mutation.payload.task, title: 'Offline edit' } } };
  assert.equal((await push([stale])).conflicts.length, 1);
  assert.equal((await call('/tasks', { token })).tasks.find(record => record.syncId === syncId).title, 'Website edit');
  const current = (await call('/tasks', { token })).tasks.find(record => record.syncId === syncId);
  const contenders = [1, 2].map(index => ({ ...stale, baseRevision: current.revision, mutationId: randomUUID(), payload: { task: { ...stale.payload.task, title: `Concurrent ${index}` } } }));
  const results = await Promise.all(contenders.map(value => push([value])));
  assert.equal(results.reduce((sum, result) => sum + result.accepted.length, 0), 1);
  await call(`/tasks/${remote._id}`, { token, method: 'DELETE' });
  assert.ok(!(await call('/tasks', { token })).tasks.some(record => record.syncId === syncId));
  const snapshot = await call('/tasks?includeDeleted=true', { token });
  assert.ok(snapshot.tasks.find(record => record.syncId === syncId).deletedAt);
  assert.equal((await push([stale])).conflicts.length, 1);
  const pull = await call('/sync/pull', { token, method: 'POST', body: {} });
  assert.ok(pull.changes.some(record => record.syncId === syncId && record.deletedAt));
  assert.equal((await call('/sync/pull', { token: b.token, method: 'POST', body: {} })).changes.length, 0);
  await call('/sync/pull', { token, method: 'POST', body: { cursor: 'bad' }, status: 400 });
  await call('/suggestions', { token, method: 'POST', body: { query: 'questions' }, status: 400 });
  const insufficient = await call('/suggestions', { token: b.token, method: 'POST', body: { consent: true, query: 'questions' } });
  assert.equal(insufficient.sources.length, 0);
  await call('/tasks', { token, method: 'POST', body: { title: 'Second task' }, status: 201 });
  await call('/suggestions', { token, method: 'POST', body: { consent: true, query: 'questions' }, status: 503 });
});
